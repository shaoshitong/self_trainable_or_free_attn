#!/usr/bin/env node
// Generates the inline HTML fragment and the Canvas component from one source. `--check` only compares.
const fs = require("fs");
const path = require("path");

const ROOT_ID = "vsa2-load-balance-root";
const here = __dirname;
const outDir = path.join(here, "..");
const read = (name) => fs.readFileSync(path.join(here, name), "utf8");

function generate() {
  const code = (read("model.js") + "\n" + read("view.js")).split("\n").filter((l) => !l.includes("// node-only")).join("\n").trim();
  const inner = "<style>\n" + read("style.css").trim() + "\n</style>\n" + read("markup.html").trim();
  if (/[`\\]|\$\{/.test(inner)) throw new Error("markup and style must stay free of backticks and backslashes");
  if (/<\/script/i.test(code)) throw new Error("script must not contain a closing script tag");
  const html =
    '<section id="' + ROOT_ID + '" aria-label="VSA2 负载均衡教学动画">\n' + inner + "\n</section>\n" +
    "<script>\n(function () {\n" + code + '\nmount(document.getElementById("' + ROOT_ID + '"));\n})();\n</script>\n';
  const canvas =
    "// @ts-nocheck\n// Generated by docs/animations/vsa2-load-balance/build.js; edit the sources there.\n" +
    'import React, { useEffect, useRef } from "react";\n\n' +
    "const MARKUP = `" + inner + "`;\n\n" + code + "\n\n" +
    "export default function App() {\n" +
    "  const root = useRef(null);\n" +
    "  useEffect(() => (root.current ? mount(root.current) : undefined), []);\n" +
    '  return React.createElement("section", { id: "' + ROOT_ID + '", "aria-label": "VSA2 负载均衡教学动画", ref: root, dangerouslySetInnerHTML: { __html: MARKUP } });\n' +
    "}\n";
  return { "vsa2-load-balance.html": html, "vsa2-load-balance.canvas.tsx": canvas };
}

function main() {
  const files = generate();
  let stale = 0;
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(outDir, name);
    if (process.argv.includes("--check")) {
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) { console.error("stale: " + name); stale++; }
    } else {
      fs.writeFileSync(file, content);
      console.log(name + " " + Buffer.byteLength(content) + " bytes");
    }
  }
  if (stale) process.exit(1);
}

if (require.main === module) main();
module.exports = { generate, ROOT_ID };
